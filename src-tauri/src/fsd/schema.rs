/// Top-level run manifest at `fsd-runs/<leader>/runs/<run_id>/manifest.json`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub(crate) struct RunManifest {
    pub run_id: String,
    pub leader_handle: String,
    /// PID of the canvas-terminal process that owns this run. `recover_runs()`
    /// uses this + `is_process_alive` to detect crashes (plan v5 §5.3).
    pub owner_pid: u32,
    /// ISO-8601. Used as the canonical sort key for retention (plan v5 §5.6 /
    /// item K) — NOT filesystem mtime, which recovery rewrites can skew.
    pub started_at: String,
    /// Heartbeat — orchestrator writes every ~10s while run is active.
    /// Recovery marks runs interrupted if `now - last_heartbeat_at > 60s`,
    /// catching orchestrator-task wedge while owning process is alive (R15).
    pub last_heartbeat_at: String,
    pub status: RunStatus,
    /// Active session/run nonces. Captured here so recovery can verify
    /// expectations on a partial run.
    pub session_nonce: String,
    pub run_nonce: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub(crate) enum RunStatus {
    /// In-flight states — `recover_runs()` marks these `Interrupted` if owner
    /// is dead OR heartbeat is stale.
    Running,
    Dispatching,
    AwaitingLeader,
    /// Terminal states — eligible for retention sweep (plan v5 §5.3).
    Done,
    Blocked,
    Cancelled,
    CapTripped,
    Interrupted,
}

impl RunStatus {
    pub fn is_active(self) -> bool {
        matches!(
            self,
            RunStatus::Running | RunStatus::Dispatching | RunStatus::AwaitingLeader
        )
    }

    pub fn is_terminal(self) -> bool {
        !self.is_active()
    }
}

/// Per-task done.json written when an assistant subprocess exits.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub(crate) struct TaskDone {
    pub task_id: String,
    pub run_id: String,
    pub turn: u32,
    pub tool: String,
    pub exit_code: Option<i32>,
    pub wallclock_ms: u64,
    pub stdout_bytes: u64,
    pub stderr_bytes: u64,
    pub stdout_path: String, // relative to fsd-runs/
    pub stderr_path: String,
    pub error: Option<String>,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn plan_command_round_trips() {
        let cmd = FsdCommand::Plan {
            env: FsdEnvelope {
                v: 1,
                cmd_id: "abc".into(),
                sn: "a3f1c92e".into(),
                rn: "7b4d8e10".into(),
                run_id: "run-1".into(),
            },
            goal: "list files".into(),
            success_criteria: vec!["all files listed".into()],
            max_turns: 3,
        };
        let json = serde_json::to_string(&cmd).unwrap();
        let parsed: FsdCommand = serde_json::from_str(&json).unwrap();
        match parsed {
            FsdCommand::Plan { env, goal, max_turns, .. } => {
                assert_eq!(env.cmd_id, "abc");
                assert_eq!(goal, "list files");
                assert_eq!(max_turns, 3);
            }
            _ => panic!("wrong variant after round-trip"),
        }
    }

    #[test]
    fn dispatch_with_tasks_round_trips() {
        let json = r#"{
            "v": 1,
            "cmd_id": "c1",
            "sn": "11111111",
            "rn": "22222222",
            "run_id": "r1",
            "type": "dispatch",
            "turn": 1,
            "tasks": [
                {"task_id": "t-1-a", "tool": "claude_code", "instance_idx": 1,
                 "prompt": "review src/lib.rs"}
            ]
        }"#;
        let cmd: FsdCommand = serde_json::from_str(json).unwrap();
        match cmd {
            FsdCommand::Dispatch { tasks, .. } => {
                assert_eq!(tasks.len(), 1);
                assert_eq!(tasks[0].task_id, "t-1-a");
                assert_eq!(tasks[0].wallclock_ms_cap, 120_000); // default
            }
            _ => panic!("wrong variant"),
        }
    }

    #[test]
    fn blocked_with_optional_fields() {
        let json = r#"{
            "v": 1, "cmd_id": "c1", "sn": "x", "rn": "y", "run_id": "r1",
            "type": "blocked",
            "reason": "auth-missing",
            "missing_capability": "gemini-cli"
        }"#;
        let cmd: FsdCommand = serde_json::from_str(json).unwrap();
        match cmd {
            FsdCommand::Blocked { reason, missing_capability, needed_user_input, .. } => {
                assert_eq!(reason, "auth-missing");
                assert_eq!(missing_capability.as_deref(), Some("gemini-cli"));
                assert_eq!(needed_user_input, None);
            }
            _ => panic!("wrong variant"),
        }
    }

    #[test]
    fn run_status_active_vs_terminal() {
        assert!(RunStatus::Running.is_active());
        assert!(RunStatus::Dispatching.is_active());
        assert!(!RunStatus::Done.is_active());
        assert!(RunStatus::Done.is_terminal());
        assert!(RunStatus::Interrupted.is_terminal());
    }
}
