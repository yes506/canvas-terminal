//! FSD wire-format schemas.
//!
//! These types mirror the TypeScript `src/types/fsd.ts` definitions; the two
//! must produce identical verdicts on the same input (per plan v5 §2 two-layer
//! validation paragraph). A future paired fuzzer asserts this invariant.
//!
//! ## Protocol grammar (plan v5 §3)
//!
//! Leaders emit single-line JSON commands prefixed with `##FSD `:
//! ```text
//! ##FSD {"v":1,"cmd_id":"...","sn":"...","rn":"...","run_id":"...",
//!        "type":"plan","goal":"...","success_criteria":[...],"max_turns":4}
//! ```
//!
//! Verbs: `plan`, `dispatch`, `done`, `blocked`. All four ship in Phase 1.

use serde::{Deserialize, Serialize};

/// Schema version. Increment for breaking changes; reject unknown versions
/// with a one-time warning per session.
pub(crate) const SCHEMA_VERSION: u32 = 1;

/// FSD multiplier tier. Matches the user spec: x1 = 4 assistants, x2 = 8,
/// x3 = 12. Phase 1 ships only `Off` and `Pilot` (single-CLI, single-assistant)
/// per plan v5 §5.1.
///
/// Currently consumed by the frontend `src/types/fsd.ts` mirror only — Rust
/// orchestrator passes tier as `u8` for IPC simplicity. Kept here as the
/// canonical schema documentation.
#[allow(dead_code)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub(crate) enum FsdTier {
    Off,
    Pilot, // Phase 1 honest label (was x1 in the user spec, but Pilot = 1+1 only)
    X1,    // Phase 2: 1 of each tool (4 assistants)
    X2,    // Phase 2: 2 of each (8)
    X3,    // Phase 3: 3 of each (12)
}

/// Which channel the leader uses to emit commands. Chip surfaces this so the
/// user knows whether MCP is active or prompt-eng is the only path.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub(crate) enum EmissionMode {
    /// Stdout `##FSD {json}` lines parsed by `fsdLineTap.ts`.
    PromptLines,
    /// Native MCP tool calls (Claude Code, Codex, etc.).
    McpTools,
    /// Both available; leader picks per emission. Orchestrator dedupes by
    /// `(run_id, cmd_id)` per plan v5 §5.5.
    Both,
    /// Toggle disabled — no path is reliable enough per Phase 0 verdict.
    Unavailable,
}

/// Every leader-emitted command carries these envelope fields.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub(crate) struct FsdEnvelope {
    /// Schema version. Reject if != SCHEMA_VERSION.
    pub v: u32,
    /// Per-command UUID generated by the leader. Orchestrator dedupes —
    /// MCP tool calls and stdout `##FSD` lines share the same `(run_id, cmd_id)`
    /// dedup key (plan v5 §5.5).
    pub cmd_id: String,
    /// 8-hex session nonce. Issued by orchestrator on `fsd_set_tier(>0)`.
    /// Mismatch → §5.2 discriminator (drop or strike-and-remind).
    pub sn: String,
    /// 8-hex run nonce. Issued at the start of each run. Mismatch → §5.2.
    pub rn: String,
    /// UUID per user prompt. Leader emits a fresh one on each `plan`.
    pub run_id: String,
}

/// All four verbs as a tagged union.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub(crate) enum FsdCommand {
    Plan {
        #[serde(flatten)]
        env: FsdEnvelope,
        /// User's prompt verbatim.
        goal: String,
        /// Free-form success criteria the leader will use for self-evaluation.
        #[serde(default)]
        success_criteria: Vec<String>,
        /// Leader-requested cap on turns; clamped server-side to ≤ MAX_TURNS_CEILING.
        #[serde(default = "default_max_turns")]
        max_turns: u32,
    },
    Dispatch {
        #[serde(flatten)]
        env: FsdEnvelope,
        /// 1-indexed turn number within the run.
        turn: u32,
        /// Per-task envelopes. Length capped at MAX_TASKS_PER_DISPATCH server-side.
        tasks: Vec<TaskSpec>,
    },
    Done {
        #[serde(flatten)]
        env: FsdEnvelope,
        /// Final user-visible answer.
        summary: String,
        /// Optional: artifact paths or citations for the user to verify.
        #[serde(default)]
        evidence: Vec<String>,
    },
    Blocked {
        #[serde(flatten)]
        env: FsdEnvelope,
        /// Machine tag, e.g. "roster-empty", "auth-missing", "leader-cant-decide".
        reason: String,
        /// Optional: missing tool/capability name.
        #[serde(default)]
        missing_capability: Option<String>,
        /// Optional: human-readable prompt for the user (Phase 3 re-entry flow).
        #[serde(default)]
        needed_user_input: Option<String>,
        /// `cmd_id` of the last successful action — debugging aid.
        #[serde(default)]
        last_cmd_id: Option<String>,
    },
}

fn default_max_turns() -> u32 {
    crate::fsd::orchestrator::MAX_TURNS_DEFAULT
}

/// One assistant's task within a `dispatch`. The leader authors the prompt;
/// the harness only validates schema and bounds.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub(crate) struct TaskSpec {
    /// Stable per-task ID (`t-<turn>-<a/b/c>`).
    pub task_id: String,
    /// Which CLI to spawn. Phase 1 Pilot accepts only the spike-selected CLI.
    pub tool: String,
    /// 1-indexed instance within the same tool (for x2/x3 multi-instance).
    pub instance_idx: u32,
    /// Free-form role descriptor (no fixed taxonomy in Phase 1).
    pub role_hint: Option<String>,
    /// Tailored prompt for this assistant.
    pub prompt: String,
    /// Optional: paths to context files the assistant should read (typically
    /// previous turn's results).
    #[serde(default)]
    pub context_refs: Vec<String>,
    /// Per-task wallclock cap. Clamped server-side.
    #[serde(default = "default_task_wallclock_ms")]
    pub wallclock_ms_cap: u64,
}

fn default_task_wallclock_ms() -> u64 {
    120_000
}

